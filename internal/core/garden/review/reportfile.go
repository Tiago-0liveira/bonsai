// Report file limits. A file over a limit is invalid, never truncated: a cut report could look clean.
const (
	MaxReportBytes     = 256 << 10
	MaxFindings        = 100
	MaxSummaryRunes    = 2000
	MaxTitleRunes      = 200
	MaxPathRunes       = 512
	MaxEvidenceRunes   = 2000
	MaxRecommendRunes  = 2000
	MaxLine            = 10_000_000
	ReportSchemaNumber = 1
)

// ReviewerRole is fixed: reviewer sessions are read-only. It is not configurable and carries no user text.
const ReviewerRole = "You are a read-only code reviewer. Do not modify the repository, its files, branches, " +
	"remotes or configuration. Write only the report file named below. Every finding must cite file evidence: a " +
	"repository-relative path, a line and the code that shows the problem."

// ReportSchemaExample is the exact shape the reviewer must write.
const ReportSchemaExample = `{
  "schema": 1,
  "summary": "one paragraph on what you reviewed and the overall result",
  "findings": [
    {
      "severity": "high | medium | low | info",
      "title": "short title",
      "path": "relative/path/in/repository.go",
      "line": 42,
      "evidence": "the code or behaviour that shows the problem",
      "recommendation": "what to change"
    }
  ]
}`

// Instructions builds the fixed reviewer instruction for the one report file. reportPath is generated by Bonsai;
// it must be a single line without control bytes. No task, issue or user text is ever added.
func Instructions(reportPath string) (string, error) {
	if reportPath == "" || strings.IndexFunc(reportPath, unicode.IsControl) >= 0 {
		return "", fmt.Errorf("%w: report path", ErrInvalid)
	}
	return ReviewerRole + "\n\nReport file: " + reportPath + "\n\nWrite exactly one JSON document of this shape " +
		"(no markdown, no other output files):\n" + ReportSchemaExample + "\n", nil
}

// Expect is what the caller knows about the run the file belongs to.
type Expect struct {
	Commit  string
	Attempt string
}

// Body is a validated, sanitized report file bound to the run it was written for.
type Body struct {
	AttemptID string
	Commit    string
	Summary   string
	Findings  []Finding
}

type fileDoc struct {
	Schema   int           `json:"schema"`
	Summary  string        `json:"summary"`
	Findings []fileFinding `json:"findings"`
}

type fileFinding struct {
	Severity       Severity `json:"severity"`
	Title          string   `json:"title"`
	Path           string   `json:"path"`
	Line           int      `json:"line"`
	Evidence       string   `json:"evidence"`
	Recommendation string   `json:"recommendation"`
}

func invalid(why string) error { return fmt.Errorf("%w: %s", ErrInvalidReport, why) }

// ParseReportFile validates a reviewer's report file strictly. Any violation yields ErrInvalidReport; the caller
// records state invalid with FailInvalid and never stores the file's text.
func ParseReportFile(data []byte, expect Expect) (Body, error) {
	if !ValidSHA(expect.Commit) || !idRE.MatchString(expect.Attempt) {
		return Body{}, fmt.Errorf("%w: expectation", ErrInvalid)
	}
	if len(data) == 0 || len(data) > MaxReportBytes {
		return Body{}, invalid("size")
	}
	if !utf8.Valid(data) || garden.RejectDuplicateJSONKeys(data) != nil {
		return Body{}, invalid("encoding")
	}
	var doc fileDoc
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&doc); err != nil {
		return Body{}, invalid("json")
	}
	if dec.Decode(new(any)) != io.EOF {
		return Body{}, invalid("trailing data")
	}
	if doc.Schema != ReportSchemaNumber || len(doc.Findings) > MaxFindings {
		return Body{}, invalid("schema")
	}
	summary, ok := cleanText(doc.Summary, MaxSummaryRunes, true)
	if !ok || summary == "" {
		return Body{}, invalid("summary")
	}
	out := Body{AttemptID: expect.Attempt, Commit: expect.Commit, Summary: summary}
	seen := map[string]bool{}
	for _, f := range doc.Findings {
		if !f.Severity.valid() || f.Line < 0 || f.Line > MaxLine {
			return Body{}, invalid("finding")
		}
		title, ok1 := cleanText(f.Title, MaxTitleRunes, false)
		evidence, ok2 := cleanText(f.Evidence, MaxEvidenceRunes, true)
		rec, ok3 := cleanText(f.Recommendation, MaxRecommendRunes, true)
		if !ok1 || !ok2 || !ok3 || title == "" || evidence == "" || !validRepoPath(f.Path) {
			return Body{}, invalid("finding")
		}
		id := FindingID(f.Path, f.Line, title, evidence)
		if seen[id] {
			continue // the same observation twice is one finding
		}
		seen[id] = true
		out.Findings = append(out.Findings, Finding{ID: id, Severity: f.Severity, Title: title, Path: f.Path,
			Line: f.Line, Evidence: evidence, Recommendation: rec})
	}
	return out, nil
}

// validRepoPath accepts only a clean, relative, forward-slash path with no control bytes.
func validRepoPath(p string) bool {
	if p == "" || utf8.RuneCountInString(p) > MaxPathRunes || strings.ContainsAny(p, "\\\x00") ||
		strings.IndexFunc(p, unicode.IsControl) >= 0 {
		return false
	}
	if strings.HasPrefix(p, "/") || (len(p) >= 2 && p[1] == ':') || path.Clean(p) != p || p == "." {
		return false
	}
	for _, seg := range strings.Split(p, "/") {
		if seg == ".." {
			return false
		}
	}
	return true
}

var (
	oscRE = regexp.MustCompile("\x1b\\][^\x07\x1b]*(?:\x07|\x1b\\\\)?")
	csiRE = regexp.MustCompile("\x1b\\[[0-?]*[ -/]*[@-~]?")
	// Two-byte escapes (ESC followed by one printable byte).
	escRE = regexp.MustCompile("\x1b[ -~]?")
)

// cleanText removes terminal escape sequences and control characters (keeping newline and tab when multiline,
// else folding line breaks into spaces), trims, and enforces the rune cap. A text over the cap is rejected.
func cleanText(s string, maxRunes int, multiline bool) (string, bool) {
	s = oscRE.ReplaceAllString(s, "")
	s = csiRE.ReplaceAllString(s, "")
	s = escRE.ReplaceAllString(s, "")
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '\n' || r == '\r' || r == '\t':
			if multiline && r != '\r' {
				b.WriteRune(r)
			} else {
				b.WriteByte(' ')
			}
		case unicode.IsControl(r),
			r >= 0x202A && r <= 0x202E, r >= 0x2066 && r <= 0x2069, r == 0x200B, r == 0xFEFF:
		default:
			b.WriteRune(r)
		}
	}
	out := strings.TrimSpace(b.String())
	if !multiline {
		out = strings.Join(strings.Fields(out), " ")
	}
	return out, utf8.RuneCountInString(out) <= maxRunes
}
